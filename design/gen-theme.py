#!/usr/bin/env python3
"""Generates Palettes.kt (Compose colors) from palettes.json.

Usage: gen-theme.py --out <dir> [--package <name>] [--palettes <palettes.json>]
Light palettes have no hover and accent-2 tokens, they fall back to the dark values of the same theme.
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
COMMON = ["accent", "on-accent", "bg", "surface", "surface-2", "border", "text", "muted", "link"]
EXTRA = ["hover", "accent-2"]
HEX = re.compile(r"^#[0-9a-f]{6}$")


def camel(token):
    head, *tail = token.split("-")
    return head + "".join(part.capitalize() for part in tail)


def color(value):
    if not HEX.match(value):
        sys.exit(f"invalid color {value}")
    return f"Color(0xFF{value[1:].upper()})"


def tokens(palette, mode, key):
    values = dict(palette[mode])
    for name in EXTRA:
        values.setdefault(name, palette["dark"][name])
    missing = [name for name in COMMON + EXTRA if name not in values]
    if missing:
        sys.exit(f"{key} {mode}: missing tokens {missing}")
    args = ", ".join(f"{camel(name)} = {color(values[name])}" for name in COMMON + EXTRA)
    return f"Tokens({args})"


def status(data, mode):
    args = ", ".join(f"{name} = {color(value)}" for name, value in data["status"][mode].items())
    return f"Status({args})"


def render(data, package):
    fields = ", ".join(f"val {camel(name)}: Color" for name in COMMON + EXTRA)
    lines = [
        "// Generated by design/gen-theme.py from design/palettes.json. Do not edit.",
        f"package {package}",
        "",
        "import androidx.compose.ui.graphics.Color",
        "",
        f"data class Tokens({fields})",
        "",
        "data class Status(val success: Color, val danger: Color, val warning: Color)",
        "",
        "data class Palette(val key: String, val name: String, val dark: Tokens, val light: Tokens)",
        "",
        "object Palettes {",
        f"    val darkStatus = {status(data, 'dark')}",
        f"    val lightStatus = {status(data, 'light')}",
        "",
        "    val all: List<Palette> = listOf(",
    ]
    for key, palette in data["palettes"].items():
        lines += [
            "        Palette(",
            f'            key = "{key}",',
            f'            name = "{palette["name"]}",',
            f"            dark = {tokens(palette, 'dark', key)},",
            f"            light = {tokens(palette, 'light', key)},",
            "        ),",
        ]
    lines += [
        "    )",
        "",
        "    fun byKey(key: String): Palette = all.firstOrNull { it.key == key } ?: all.first()",
        "}",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True)
    parser.add_argument("--package", default="org.elektronnet.mobile.ui.theme")
    parser.add_argument("--palettes", default=os.path.join(HERE, "palettes.json"))
    args = parser.parse_args()
    with open(args.palettes) as f:
        data = json.load(f)
    target = os.path.join(args.out, *args.package.split("."))
    os.makedirs(target, exist_ok=True)
    with open(os.path.join(target, "Palettes.kt"), "w") as f:
        f.write(render(data, args.package))


if __name__ == "__main__":
    main()
