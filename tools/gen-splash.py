#!/usr/bin/env python3
"""Writes the splash theme styles from design/palettes.json: values/ (window background) and values-v31/ (splash screen background). With --check it only compares."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "app", "src", "main", "res")


def render(splash):
    data = json.load(open(os.path.join(ROOT, "design", "palettes.json")))
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/gen-splash.py from design/palettes.json. Do not edit. -->", "<resources>"]
    for key, palette in data["palettes"].items():
        for mode in ("dark", "light"):
            bg = palette[mode]["bg"]
            out.append(f'    <style name="Theme.Elektron.Splash.{key}.{mode}" parent="Theme.Elektron">')
            out.append(f'        <item name="android:windowBackground">{bg}</item>')
            if splash:
                out.append(f'        <item name="android:windowSplashScreenBackground">{bg}</item>')
            out.append("    </style>")
    out.append("</resources>")
    return "\n".join(out) + "\n"


def targets():
    return [
        (os.path.join(RES, "values", "themes_splash.xml"), render(False)),
        (os.path.join(RES, "values-v31", "themes_splash.xml"), render(True)),
    ]


def main():
    check = "--check" in sys.argv
    for path, text in targets():
        if check:
            if not os.path.isfile(path) or open(path).read() != text:
                sys.exit(f"{path} is out of date, run tools/gen-splash.py")
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w").write(text)
    if check:
        print("splash themes ok")


if __name__ == "__main__":
    main()
