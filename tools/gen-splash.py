#!/usr/bin/env python3
"""Writes app/src/main/res/values/themes_splash.xml from design/palettes.json. With --check it only compares."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def render():
    data = json.load(open(os.path.join(ROOT, "design", "palettes.json")))
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/gen-splash.py from design/palettes.json. Do not edit. -->", "<resources>"]
    for key, palette in data["palettes"].items():
        for mode in ("dark", "light"):
            bg = palette[mode]["bg"]
            out += [
                f'    <style name="Theme.Elektron.Splash.{key}.{mode}" parent="Theme.Elektron">',
                f'        <item name="android:windowBackground">{bg}</item>',
                f'        <item name="android:windowSplashScreenBackground">{bg}</item>',
                "    </style>",
            ]
    out.append("</resources>")
    return "\n".join(out) + "\n"


def main():
    target = os.path.join(ROOT, "app", "src", "main", "res", "values", "themes_splash.xml")
    text = render()
    if "--check" in sys.argv:
        if not os.path.isfile(target) or open(target).read() != text:
            sys.exit("themes_splash.xml is out of date, run tools/gen-splash.py")
        print("splash themes ok")
        return
    open(target, "w").write(text)


if __name__ == "__main__":
    main()
